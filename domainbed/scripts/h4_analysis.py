"""H4, "Sample-level dual variables": per-run table, tables and figure from the raw runs.

    python -m domainbed.scripts.h4_analysis

Reads every finished run under outputs/h4 (results.jsonl, and selection.jsonl of the
runs with selection by dual variables); writes results/h4_runs.csv (one row per run),
results/h4_tables.md and paper/figures/fig_h4_selection.{pdf,png}.

Per run, besides the columns of stream_analysis.py: memory, selection ('random',
'dual' or '' for fine-tuning) and, for selection by dual variables, averaged over the
three times a task's examples are first stored (end of phases 1 to 3):

    pool_* / kept_*   the 1,000 candidates of the task / the candidates stored.
                      The candidates are a uniform sample of the task's stream, so
                      pool_* is what random selection stores in expectation.
    *_loss            mean cross-entropy under the model at the time of selection
    *_wrong           share misclassified at that time (percent)
    *_minority        share of the class that is the minority among the candidates (percent)
    dual_nonzero      share of candidates with a positive dual variable (percent)

All differences are paired by seed; "a ± b" is mean ± standard error over the ten
seeds; bold = larger than two standard errors.
"""
import json
from pathlib import Path

import numpy as np
import pandas as pd

from domainbed.scripts import paper_assets as pa
from domainbed.scripts import stream_analysis as sa
from domainbed.scripts.paper_assets import CYAN, NIGHT, ORANGE, RED, plt

ROOT = Path('outputs/h4')
STREAMS = ['skew0.9', 'agrate', 'aglen', 'rounds']
NAME = {'skew0.9': 'skew:0.9', 'agrate': 'agrate', 'aglen': 'aglen', 'rounds': 'rounds'}
MEMORIES = [50, 200]
ALGS = [('PDCL_RS', 'PDCL'), ('ER', 'Replay (ER)')]
COLOR = {'PDCL_RS': RED, 'ER': CYAN}
CELLS = [(g, m, a) for g in STREAMS for m in MEMORIES for a, _ in ALGS]
method = lambda a, m, sel: f'{a}__m{m}_{sel}'
SEL_KEYS = ['pool_loss', 'kept_loss', 'pool_wrong', 'kept_wrong', 'pool_minority', 'kept_minority',
            'dual_nonzero', 'kept_dual_nonzero']


# --------------------------------------------------------------------------
# raw runs -> one row per run
# --------------------------------------------------------------------------
def selection_row(path):
    recs = [json.loads(l) for l in open(path)]
    assert len(recs) == 3, path
    out = {k: [] for k in SEL_KEYS}
    for r in recs:
        binder_is_minority = r['pool_binder'] < 0.5
        for name in ('pool', 'kept'):
            b = r[f'{name}_binder']
            out[f'{name}_minority'].append(100 * (b if binder_is_minority else 1 - b))
            out[f'{name}_loss'].append(r[f'{name}_loss'])
            out[f'{name}_wrong'].append(100 * r[f'{name}_wrong'])
        out['dual_nonzero'].append(100 * r['dual_nonzero'])
        out['kept_dual_nonzero'].append(100 * r['kept_dual_nonzero'])
    return {k: float(np.mean(v)) for k, v in out.items()}


def load():
    rows = []
    for done in sorted(ROOT.rglob('done')):
        d = done.parent
        recs = [json.loads(l) for l in open(d / 'results.jsonl')]
        hp, alg = recs[-1]['hparams'], recs[-1]['args']['algorithm']
        replay = alg != 'Finetune'
        row = {'group': d.parent.parent.name, 'method': d.parent.name} | sa.run_row(recs)
        row['memory'] = hp['buffer_size'] if replay else 0
        row['selection'] = (hp.get('selection') or 'random') if replay else ''
        assert (d / 'selection.jsonl').exists() == (row['selection'] == 'dual'), d
        if row['selection'] == 'dual':
            row |= selection_row(d / 'selection.jsonl')
        rows.append(row)
    return pd.DataFrame(rows)


# --------------------------------------------------------------------------
# statistics
# --------------------------------------------------------------------------
def seeds(df, group, meth, value='final_acc'):
    d = df[(df['group'] == group) & (df['method'] == meth)]
    assert len(d) == 10, (group, meth, len(d))
    return d.set_index('seed')[value].sort_index()


def ms(x):
    x = np.asarray(x, dtype=float)
    return x.mean(), x.std(ddof=1) / np.sqrt(len(x))


def stat(df, group, meth, value='final_acc'):
    return ms(seeds(df, group, meth, value))


def diff(df, group, a, b, value='final_acc'):
    return ms(seeds(df, group, a, value) - seeds(df, group, b, value))


def pm(m, s, nd=2):
    return f'{m:.{nd}f} ± {s:.{nd}f}'


def spm(m, s, nd=2):
    t = f'{m:+.{nd}f} ± {s:.{nd}f}'
    return f'**{t}**' if abs(m) > 2 * s else t


def md(header, rows):
    out = ['| ' + ' | '.join(header) + ' |', '|' + '---|' * len(header)]
    return '\n'.join(out + ['| ' + ' | '.join(str(c) for c in r) + ' |' for r in rows]) + '\n'


def tables(df):
    out = ['# H4: sample-level dual variables, tables\n',
           'Generated by `python -m domainbed.scripts.h4_analysis` from the raw runs under '
           '`outputs/h4`. Ten seeds per cell; "a ± b" is mean ± standard error over seeds; '
           'differences are paired by seed; bold = larger than two standard errors. '
           'Accuracies in percent, differences in points.\n']

    out.append('## 1. Selection by dual variables minus random selection (the pre-registered outcome)\n')
    rows, null, pos, neg = [], 0, 0, 0
    for g, m, a in CELLS:
        d, r = method(a, m, 'dual'), method(a, m, 'random')
        dm, ds = diff(df, g, d, r)
        null += abs(dm) <= 2 * ds
        pos += dm > 2 * ds
        neg += dm < -2 * ds
        rows.append([NAME[g], m, dict(ALGS)[a], pm(*stat(df, g, r)), pm(*stat(df, g, d)), spm(dm, ds),
                     spm(*diff(df, g, d, r, 'forgetting')), spm(*diff(df, g, d, r, 'learned_acc'))])
    out.append(md(['stream', 'memory', 'method', 'final acc., random', 'final acc., dual',
                   'dual − random, final acc.', 'dual − random, forgetting',
                   'dual − random, learned acc.'], rows))
    verdict = {'null': int(null), 'positive': int(pos), 'negative': int(neg)}
    out.append(f'Cells of 16 with final accuracy within two standard errors: **{null}**; '
               f'dual better: {pos}; dual worse: {neg}. Pre-registered prediction: at least 12 nulls '
               f'— **{"holds" if null >= 12 else "fails"}**.\n')
    pooled = []
    for a, lab in ALGS:
        for value in ('final_acc', 'forgetting'):
            per_seed = np.mean([seeds(df, g, method(a, m, 'dual'), value).values
                                - seeds(df, g, method(a, m, 'random'), value).values
                                for g in STREAMS for m in MEMORIES], axis=0)
            pooled.append([lab, value, spm(*ms(per_seed))])
    out.append('Average over the eight cells of each method (per seed, then over seeds; not pre-registered):\n')
    out.append(md(['method', 'metric', 'dual − random'], pooled))

    out.append('## 2. Each setting against fine-tuning, final accuracy\n')
    rows = []
    for g in STREAMS:
        rows.append([NAME[g], 'Fine-tuning', '', pm(*stat(df, g, 'Finetune')), '', pm(*stat(df, g, 'Finetune', 'forgetting'))])
        for m in MEMORIES:
            for a, lab in ALGS:
                for sel in ('random', 'dual'):
                    me = method(a, m, sel)
                    rows.append([NAME[g], f'{lab}, memory {m}', sel, pm(*stat(df, g, me)),
                                 spm(*diff(df, g, me, 'Finetune')), pm(*stat(df, g, me, 'forgetting'))])
    out.append(md(['stream', 'method', 'selection', 'final acc.', '− fine-tuning', 'forgetting'], rows))

    out.append('## 3. What the dual variables select\n')
    out.append('Stored examples of a task at the end of its phase ("kept") against its 1,000 candidates '
               '("pool" = what random selection stores in expectation), averaged over phases 1 to 3.\n')
    rows = []
    for g, m, a in CELLS:
        d = method(a, m, 'dual')
        s = lambda k, nd=2: pm(*stat(df, g, d, k), nd)
        rows.append([NAME[g], m, dict(ALGS)[a], s('dual_nonzero', 1), s('pool_loss'), s('kept_loss'),
                     s('pool_wrong', 1), s('kept_wrong', 1), s('pool_minority', 1), s('kept_minority', 1)])
    out.append(md(['stream', 'memory', 'method', 'candidates with dual > 0 (%)', 'loss, pool', 'loss, kept',
                   'misclassified, pool (%)', 'misclassified, kept (%)', 'minority class, pool (%)',
                   'minority class, kept (%)'], rows))
    Path('results/h4_tables.md').write_text('\n'.join(out))
    return verdict


# --------------------------------------------------------------------------
# figure
# --------------------------------------------------------------------------
def figure(df):
    fig, axes = plt.subplots(2, 2, figsize=(180 * pa.MM, 125 * pa.MM))
    for ax, letter in zip(axes.flat, 'abcd'):
        ax.grid(color='gray', alpha=0.7, linewidth=0.4, zorder=0)
        ax.text(-0.24, 1.06, letter, transform=ax.transAxes, fontweight='bold', fontsize=9)
    cells = [(g, m) for g in STREAMS for m in MEMORIES]
    x = np.arange(len(cells))
    for ax, value, ylabel in ((axes[0, 0], 'final_acc', 'Dual − Random Selection,\nFinal Accuracy (points)'),
                              (axes[0, 1], 'forgetting', 'Dual − Random Selection,\nForgetting (points)')):
        ax.axhline(0, color=ORANGE, linewidth=1.1, zorder=2, label='Random Selection')
        for (a, lab), off in zip(ALGS, (-0.15, 0.15)):
            v = np.array([diff(df, g, method(a, m, 'dual'), method(a, m, 'random'), value) for g, m in cells])
            ax.errorbar(x + off, v[:, 0], yerr=v[:, 1], color=COLOR[a], marker='o', linestyle='none', capsize=2,
                        zorder=3, markeredgecolor=NIGHT, markeredgewidth=0.4, label=lab)
        ax.set_ylabel(ylabel)
    for ax, key, ylabel in ((axes[1, 0], 'minority', 'Minority Class among\nStored Examples (%)'),
                            (axes[1, 1], 'loss', 'Loss of Stored Examples\nat Selection')):
        for name, color, lab, off in (('pool', ORANGE, 'Random Selection (Candidates)', -0.15),
                                      ('kept', NIGHT, 'Selection by Dual Variables', 0.15)):
            # both methods pooled per seed: the candidates of a task do not depend on the method
            v = np.array([ms(np.mean([seeds(df, g, method(a, m, 'dual'), f'{name}_{key}').values
                                      for a, _ in ALGS], axis=0)) for g, m in cells])
            ax.errorbar(x + off, v[:, 0], yerr=v[:, 1], color=color, marker='o', linestyle='none', capsize=2,
                        zorder=3, markeredgecolor=NIGHT, markeredgewidth=0.4, label=lab)
        ax.set_ylabel(ylabel)
        ax.set_ylim(bottom=0)
    for ax in axes.flat:
        ax.set_xticks(x)
        ax.set_xticklabels([str(m) for _, m in cells])
        for i, g in enumerate(STREAMS):
            ax.text(2 * i + 0.5, -0.13, NAME[g], transform=ax.get_xaxis_transform(), ha='center', va='top')
        ax.set_xlabel('Stream and Memory Size', labelpad=14)
        ax.legend(loc='lower center', bbox_to_anchor=(0.55, 1.0), ncol=3, columnspacing=1.0, handlelength=1.4)
    fig.tight_layout(pad=0.6, w_pad=2.0, h_pad=1.5)
    for ext in ('pdf', 'png'):
        fig.savefig(pa.FIG / f'fig_h4_selection.{ext}', dpi=300)
    plt.close(fig)


def main():
    pa.style()
    df = load()
    assert len(df) == 360, len(df)
    df.to_csv('results/h4_runs.csv', index=False)
    verdict = tables(df)
    figure(df)
    print(f'{len(df)} runs; cells null/positive/negative: {verdict}')


if __name__ == '__main__':
    main()
